"""PostgreSQL adapter for the research repository's parameterized SQL statements."""
import re
from contextlib import contextmanager
from pathlib import Path


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


class Cursor:
    def __init__(self, cursor, generated_id=False):
        self.cursor=cursor
        self.lastrowid=cursor.fetchone()['id'] if generated_id else None

    def fetchone(self):
        row=self.cursor.fetchone()
        return Row(row) if row is not None else None

    def fetchall(self):
        return [Row(row) for row in self.cursor.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())


def translate(sql):
    # Only internal repository SQL uses this adapter; data is always parameterized.
    ignore='INSERT OR IGNORE INTO' in sql
    sql=sql.replace('INSERT OR IGNORE INTO','INSERT INTO').replace('?', '%s')
    if ignore:
        sql=sql.rstrip().rstrip(';')+' ON CONFLICT DO NOTHING'
    generated=bool(re.match(r'\s*INSERT INTO (fetches|collection_runs)\s*\(',sql,re.I))
    if generated:
        sql+=' RETURNING id'
    return sql,generated


def schema_sql(sqlite_schema):
    sql=sqlite_schema.replace('PRAGMA foreign_keys=ON;','').replace('CREATE VIEW IF NOT EXISTS','CREATE OR REPLACE VIEW')
    sql=sql.replace('id INTEGER PRIMARY KEY','id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    sql=sql.replace('fetch_id INTEGER','fetch_id BIGINT').replace(' BLOB',' BYTEA').replace(' REAL',' DOUBLE PRECISION')
    return sql


class PostgresStore:
    dialect='postgres'

    def __init__(self,url,schema):
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError:
            raise RuntimeError('Use research/.venv/bin/python; psycopg is required for hosted PostgreSQL') from None
        try:
            # SSL is required. Credentials stay in the driver, never in CLI output.
            self.connection=psycopg.connect(url,autocommit=True,row_factory=dict_row,
                                           sslmode='require',connect_timeout=15)
            self.transactions=[]
            with self.connection.transaction():
                self.connection.execute('CREATE SCHEMA IF NOT EXISTS market_research')
                self.connection.execute('SET search_path TO market_research')
                self.connection.execute(schema_sql(schema))
        except Exception:
            if hasattr(self,'connection'):self.connection.close()
            raise RuntimeError('Hosted PostgreSQL connection/schema setup failed. Check DATABASE_URL, network access, SSL and schema permissions.') from None

    def ensure_capacity(self, incoming_bytes=0):
        # Conservative application limit, not a substitute for the provider's Free plan.
        used=self.connection.execute('SELECT pg_database_size(current_database()) AS bytes').fetchone()['bytes']
        if used + incoming_bytes >= 300_000_000:
            raise RuntimeError('Free-data storage budget reached (300 MB). Collection stopped; no upgrade or deletion performed.')

    def execute(self,sql,params=()):
        query,generated=translate(sql)
        return Cursor(self.connection.execute(query,params),generated)

    def executemany(self,sql,rows):
        query,generated=translate(sql)
        if generated:raise ValueError('Batch inserts cannot request generated identifiers')
        with self.connection.cursor() as cursor:
            cursor.executemany(query,rows)

    def __enter__(self):
        transaction=self.connection.transaction()
        transaction.__enter__()
        self.transactions.append(transaction)
        return self

    def __exit__(self,kind,value,traceback):
        return self.transactions.pop().__exit__(kind,value,traceback)

    def close(self):
        self.connection.close()

    @contextmanager
    def collector_lock(self):
        # Use a direct/session connection, not transaction pooling.
        acquired=self.connection.execute('SELECT pg_try_advisory_lock(918273645) AS acquired').fetchone()['acquired']
        if not acquired:raise RuntimeError('Another collector or migration holds the database lock')
        try:yield
        finally:self.connection.execute('SELECT pg_advisory_unlock(918273645)')


def configured_url():
    import os
    values={}
    try:
        from dotenv import dotenv_values
        root=Path(__file__).resolve().parents[2]
        values.update(dotenv_values(root/'.env'))
        values.update(dotenv_values(root/'.env.local'))
    except ImportError:
        pass
    # Session advisory locks and schema setup require an unpooled connection.
    url=(os.environ.get('DATABASE_URL_UNPOOLED') or os.environ.get('DATABASE_URL')
         or values.get('DATABASE_URL_UNPOOLED') or values.get('DATABASE_URL'))
    if not url:
        raise RuntimeError('DATABASE_URL is not configured. Link Neon or add a hosted connection to .env. No local database fallback is used.')
    if not url.startswith(('postgresql://','postgres://')):
        raise RuntimeError('DATABASE_URL must be a PostgreSQL connection URL')
    return url
